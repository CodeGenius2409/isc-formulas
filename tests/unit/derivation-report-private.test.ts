// Writes reports/derivations.md. It counts how often each derivation appears in the private analysis, and keeps only
// the counts. Only when asked: WRITE_DERIVATION_REPORT=1 npx vitest run tests/unit/derivation-report-private.test.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { describe, it } from 'vitest';
import { DERIVATIONS } from '../../src/data/derivations';
import { marksOf } from '../../src/data/derivations/types';
import { DERIVATION_SHARE } from '../../src/practice/bank/paper';

const LABEL = { physics: 'Physics', chemistry: 'Chemistry', mathematics: 'Mathematics', computerscience: 'Computer Science' };

describe.skipIf(!process.env.WRITE_DERIVATION_REPORT)('the derivations report', () => {
  it('writes it', () => {
    const { records } = JSON.parse(readFileSync('data-private/question-analysis.json', 'utf8')) as { records: { subject: string; text: string; context?: string; outOfSyllabus?: boolean }[] };
    const count = (d: (typeof DERIVATIONS)[number]) => records.filter((r) => r.subject === d.subject && !r.outOfSyllabus && d.seen.test(`${r.context ?? ''} ${r.text}`)).length;
    const lines = [
      '# Derivations',
      '',
      'The derivations and proofs the 2028 syllabus expects, from its "derive" lines and the paper analysis. Generated by `tests/unit/derivation-report-private.test.ts`. This holds counts only, and no wording from any paper.',
      '',
      `**${DERIVATIONS.length} derivations.** Each has a bank question, so it can be asked at 0% generated, and blueprints that ask it in the other ways the papers do: from a stated start, with its assumptions, with a step missing, with a mistake to find where one was written, and with "hence calculate" where one fits.`,
      '',
      '"In the papers" counts the analysed question parts whose wording matches it. It\'s a guide, as a short or OCR-damaged part can be missed, and a broad match can overcount.',
      '',
      `"Checked" means both sides of the result were evaluated by mathjs at random values and agreed (\`tests/unit/derivations.test.ts\`), and that their units matched where the expression allows it. **${DERIVATIONS.filter((d) => d.check).length} of ${DERIVATIONS.length}** are checked like this.`,
      '',
      '## Share of derivations in mock papers',
      '',
      'At each mark value, from the board and specimen papers. A mock paper follows these.',
      '',
      '| Subject | Marks: share |',
      '| --- | --- |',
      ...(Object.entries(DERIVATION_SHARE) as [keyof typeof LABEL, Record<number, number>][]).map(([s, shares]) => `| ${LABEL[s]} | ${Object.entries(shares).map(([m, x]) => `${m} marks: ${Math.round(x * 100)}%`).join(', ') || 'None in the papers'} |`),
      '',
    ];
    for (const subject of ['physics', 'chemistry', 'mathematics', 'computerscience'] as const) {
      lines.push(`## ${LABEL[subject]}`, '', '| Class and topic | Derivation | Marks | In the papers | Checked | Ways beyond the plain one |', '| --- | --- | ---: | ---: | --- | --- |');
      for (const d of DERIVATIONS.filter((x) => x.subject === subject)) {
        const ways = ['other wording', 'missing step', ...(d.error ? ['find the error'] : []), ...(d.hence ? ['hence calculate'] : []), ...(d.drawIt ? ['draw and derive'] : [])].join(', ');
        lines.push(`| ${d.level} ${d.unit}${d.topic} | ${d.what} | ${marksOf(d)} | ${count(d)} | ${d.check ? 'Yes' : 'No'} | ${ways} |`);
      }
      lines.push('');
    }
    const unchecked = DERIVATIONS.filter((d) => !d.check);
    lines.push('## What couldn\'t be checked by machine', '', 'These results aren\'t an equation between quantities that can be evaluated: they\'re a law, a logical argument or a general form. Their steps were read through by hand instead.', '', ...unchecked.map((d) => `- ${LABEL[d.subject]}: ${d.what}. Result: ${d.result}`), '');
    lines.push('A numerical check also can\'t tell that each step leads to the next. It shows the result is right, and the steps were read by hand. A few checks, marked in the data, test a specific case or a standard identity, such as a determinant with chosen values.', '');
    writeFileSync('reports/derivations.md', lines.join('\n'));
  });
});
