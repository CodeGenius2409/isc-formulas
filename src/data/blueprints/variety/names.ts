export function nameOf(_entry: string, _symbol: string, label: string): string {
  const better = BETTER[label];
  if (better) return better;
  // A bare symbol or a probability reads as "the value of x" and "the value of P(A)".
  return /^[a-z]$|^[PE]\(/.test(label) ? `value of ${label}` : label;
}
