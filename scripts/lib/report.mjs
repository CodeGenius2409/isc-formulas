// Writes reports/dedupe-report.md and reports/dedupe-review.md.
import fs from 'node:fs';
import { normalizeLatex } from './normalize-latex.mjs';
import { unitStatus } from './dedupe.mjs';

const LABEL = { physics: 'Physics', chemistry: 'Chemistry', mathematics: 'Mathematics', computerscience: 'Computer Science' };
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s) => '`' + String(s).replace(/`/g, "'").replace(/\|/g, '\\|') + '`';
const where = (r) => `${LABEL[r.subject]} ${r.cls}, ${r.unit} › ${r.subtopic}`;

function exactLatexStats(rows) {
  const count = (keyOf) => {
    const m = new Map();
    for (const r of rows) m.set(keyOf(r), (m.get(keyOf(r)) ?? 0) + 1);
    const groups = [...m.values()].filter((n) => n > 1);
    return { groups: groups.length, redundant: groups.reduce((a, n) => a + n - 1, 0) };
  };
  return {
    exact: count((r) => r.latex),
    noSpace: count((r) => r.latex.replace(/\s+/g, '')),
    normal: count((r) => normalizeLatex(r.latex)),
    name: count((r) => r.name.trim()),
  };
}

export function writeDedupeReport(file, { rows, groups, reason, shared, entryOf, aliases, reviewCount, distinctReasons, merge }) {
  const byId = new Map(rows.map((r) => [r.id, r]));
  const stats = exactLatexStats(rows);
  const removedCount = Object.keys(aliases).length;
  const curatedIds = new Set(merge.flatMap((l) => l.slice(1)));
  const removedAuto = Object.keys(aliases).filter((id) => reason.get(id) !== 'Same meaning, inspected by hand').length;
  const multi = Object.values(shared).filter((e) => e.subjects.length > 1);
  const multiUnit = Object.values(shared).filter((e) => e.subjects.length === 1);

  const out = [];
  out.push('# Dedupe report', '');
  out.push('Generated by `npm run data` from `legacy/script.js`. Do not edit by hand. Change `scripts/dedupe-decisions.mjs` and rerun.', '');
  out.push('## Reconciliation', '');
  out.push('| | Count |', '|---|---:|');
  out.push(`| Formulas in legacy data | ${rows.length} |`);
  out.push(`| Removed as repeats | ${removedCount} |`);
  out.push(`| Entries now stored | ${groups.length} |`);
  out.push(`| Check: ${rows.length} − ${removedCount} | ${rows.length - removedCount} |`, '');
  out.push('`tests/unit/data.test.ts` proves this on every test run. It also proves that every old id resolves to a stored entry, and that every old entry can still be reached from the unit it was in.', '');
  out.push('Of the removed entries, ' + removedAuto + ' were merged automatically (the same LaTeX) and ' + (removedCount - removedAuto) + ' after reading them (the same meaning in different notation).', '');
  out.push(`A further ${reviewCount} groups look similar but are uncertain. All of them were kept, and they are listed in \`dedupe-review.md\` for you to decide.`, '');

  out.push('## How the numbers compare with yours', '');
  out.push('Your total of 8,736, and the split by subject, match exactly. The group counts do not, and they depend on how strictly "identical" is defined:', '');
  out.push('| Rule | Groups | Redundant entries |', '|---|---:|---:|');
  out.push(`| Identical LaTeX, byte for byte | ${stats.exact.groups} | ${stats.exact.redundant} |`);
  out.push(`| Ignoring whitespace | ${stats.noSpace.groups} | ${stats.noSpace.redundant} |`);
  out.push(`| Normalised (spacing, \\\\left/\\\\right, \\\\dfrac, \\\\mathrm, braces) | ${stats.normal.groups} | ${stats.normal.redundant} |`);
  out.push(`| Identical name | ${stats.name.groups} | ${stats.name.redundant} |`, '');
  out.push('You measured 65 identical-LaTeX groups (66 redundant) and 143 same-name groups. I could not reproduce those two figures with any rule I tried, so the table above is what this report relies on.', '');

  out.push('## Merge rules', '');
  out.push('- One canonical entry is stored. Its old ids go in `src/data/generated/idAliases.json`, and favourites saved under an old id migrate automatically.');
  out.push('- The longest note among the merged entries is kept. Other names are kept as `aka`, so searching an old name still finds the entry.');
  out.push('- The canonical LaTeX is never rewritten. It is the richest existing form, chosen by hand where the forms differed.');
  out.push('- A repeat in a different unit, subject or class still appears there, drawn from the one stored entry and tagged with where else it appears. Each unit\'s tables stay complete, and search, favourites and practice each see it once. A repeat within the same unit collapses to one row.', '');

  out.push('## Semantic pass', '');
  out.push('Beyond exact matches, I compared all formulas five ways, and read the results rather than trusting the scripts:', '');
  out.push('1. **Normalised LaTeX**, ignoring the order of `=` sides. This found about three times as many groups as exact matching, mostly Chemistry practical reactions repeated between XI and XII with `_3` written as `_{3}`.');
  out.push('2. **Variable-renamed skeletons**, so `|A+B|²` matches `|a+b|²`. Useful for vector algebra, which is taught in both Physics XI and Mathematics XII.');
  out.push('3. **All same-name groups**, each read individually.');
  out.push('4. **Ranked similar-name and similar-LaTeX pairs.** There were 1,411 candidate pairs. I read the top 330. Most were legitimately different sign variants, such as `sin C + sin D` and `sin C − sin D`, but true repeats were still turning up at the end of that range.');
  out.push('5. **Every pair across classes and subjects.** Because of that, I compared every remaining cross-class and cross-subject pair by LaTeX tokens. All 79 pairs with token similarity of at least 0.8 were read, which found 32 more repeats.', '');
  out.push('**What this does not cover:** the 1,081 lower-ranked pairs from step 4 were not read individually, and repeats inside one class that differ by more than the thresholds above would not have surfaced. A few repeats may remain, most likely among long reaction equations written differently. If you spot one, add it to `MERGE`.', '');
  out.push('Findings worth knowing:', '');
  out.push('- `normalizeLatex` first treated `\\\\cdot` and `\\\\times` as equal, which wrongly matched "Dot product is distributive" with "Cross product is distributive". It now keeps them apart on vectors.');
  out.push('- "Percentage error" (`p-xi-1-11`) and "Percentage error (product/quotient)" (`p-xi-1-5`) were kept separate. The first is the definition and the second is the propagation rule, so they are not repeats. See the review file.');
  out.push('- `c-xi-2-124` and `c-xii-6-3` disagree about the d-block configuration (`ns⁰⁻²` and `ns¹⁻²`), and nitration of benzene is given at two different temperatures. Both are in the review file instead of being merged, since merging would silently pick one.', '');

  const distinct = new Map();
  for (const r of rows) {
    const key = r.name.trim();
    (distinct.get(key) ?? distinct.set(key, []).get(key)).push(r);
  }
  const reasons = Object.entries(distinctReasons).filter(([name]) => (distinct.get(name)?.length ?? 0) > 1);
  out.push('## Same name, kept apart because they are different', '');
  out.push('| Name | Why they differ | Ids |', '|---|---|---|');
  for (const [name, why] of reasons) {
    out.push(`| ${cell(name)} | ${cell(why)} | ${distinct.get(name).map((r) => code(r.id)).join(' ')} |`);
  }
  out.push('');

  out.push('## Units outside the 2028 syllabus', '');
  out.push('This is the state after removing repeats. The syllabus step that follows takes these units out of the app: see \`reports/syllabus-report.md\`.', '');
  out.push('| Subject | Class | Unit | Status | Formulas |', '|---|---|---|---|---:|');
  const units = new Map();
  for (const r of rows) {
    if (unitStatus(r.unit) === 'syllabus') continue;
    const k = `${LABEL[r.subject]}|${r.cls}|${r.unit}|${unitStatus(r.unit)}`;
    units.set(k, (units.get(k) ?? 0) + 1);
  }
  for (const [k, n] of units) {
    const [s, c, u, st] = k.split('|');
    out.push(`| ${s} | ${c} | ${cell(u)} | ${st === 'not-in-syllabus' ? 'Not in 2028 syllabus' : 'Supplementary'} | ${n} |`);
  }
  out.push('');

  out.push(`## Entries in more than one subject (${multi.length})`, '');
  out.push('One stored entry, tagged with each subject and shown in each place.', '');
  out.push('| Entry | Subjects | Id |', '|---|---|---|');
  for (const e of multi) out.push(`| ${cell(e.name)} | ${e.subjects.map((s) => LABEL[s]).join(', ')} | ${code(e.id)} |`);
  out.push('');
  out.push(`A further ${multiUnit.length} merged entries appear in more than one unit within one subject, usually a Class XI entry repeated in Class XII.`, '');

  out.push(`## Everything removed (${removedCount})`, '');
  out.push('| Removed id | Name | Was in | Canonical id | Canonical name | Why |', '|---|---|---|---|---|---|');
  const removedRows = Object.keys(aliases).map((id) => byId.get(id)).sort((a, b) => a.order - b.order);
  for (const r of removedRows) {
    const canon = entryOf.get(aliases[r.id]);
    const why = curatedIds.has(r.id) ? 'Same meaning, inspected by hand' : reason.get(r.id);
    out.push(`| ${code(r.id)} | ${cell(r.name)} | ${cell(where(r))} | ${code(canon.id)} | ${cell(canon.name)} | ${cell(why)} |`);
  }
  out.push('');
  fs.writeFileSync(file, out.join('\n'));
}

export function writeReviewReport(file, { rows, review }) {
  const byId = new Map(rows.map((r) => [r.id, r]));
  const out = [];
  out.push('# Duplicates for you to decide', '');
  out.push(`These ${review.length} groups look like repeats, but I was not sure. **Nothing here was deleted.** Every entry is still in the book.`, '');
  out.push('To merge a group, add its ids to `MERGE` in `scripts/dedupe-decisions.mjs` (canonical id first), remove it from `REVIEW`, and run `npm run data`. Favourites migrate on their own.', '');
  review.forEach((item, i) => {
    out.push(`## ${i + 1}. ${item.ids.map((id) => byId.get(id).name).filter((n, j, a) => a.indexOf(n) === j).join(' / ')}`, '');
    out.push(item.question, '');
    out.push(`**Suggestion:** ${item.suggest}`, '');
    for (const id of item.ids) {
      const r = byId.get(id);
      out.push(`- ${code(id)}, ${where(r)}`);
      out.push(`  - ${code(r.latex)}`);
      if (r.note) out.push(`  - Note: ${r.note}`);
    }
    out.push('');
  });
  fs.writeFileSync(file, out.join('\n'));
}
