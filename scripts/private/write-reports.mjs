// Turns the private analysis into reports/question-analysis.md and reports/physics-visuals.md.
// What leaves here is counts and references to paper and question numbers. No wording from any paper.
import fs from 'node:fs';

const { records, unanalysed, paperStats } = JSON.parse(fs.readFileSync('data-private/question-analysis.json', 'utf8'));
const blueprints = JSON.parse(fs.readFileSync('data-private/blueprint-tags.json', 'utf8'));
const coverage = JSON.parse(fs.readFileSync('data-private/blueprint-coverage.json', 'utf8'));

const SUBJECTS = ['physics', 'chemistry', 'mathematics', 'computerscience'];
const LABEL = { physics: 'Physics', chemistry: 'Chemistry', mathematics: 'Mathematics', computerscience: 'Computer Science' };
const KIND = { mcq: 'Multiple choice', assertion: 'Assertion and reason', numerical: 'Numerical', derivation: 'Derivation', proof: 'Proof', reason: 'Give reasons', distinguish: 'Distinguish between', definition: 'Definition or recall', short: 'Short answer', reaction: 'Reaction or equation', structure: 'Structure or shape', output: 'Write the output', complete: 'Complete the program', program: 'Program writing', boolean: 'Boolean algebra', diagram: 'Diagram-based', case: 'Case or passage', match: 'Match the columns', fill: 'Fill in the blank' };

const tally = (list, f) => {
  const m = new Map();
  for (const x of list) m.set(f(x), (m.get(f(x)) ?? 0) + 1);
  return [...m].sort((a, b) => b[1] - a[1]);
};
const table = (head, rows) => [`| ${head.join(' | ')} |`, `| ${head.map((_, i) => (i ? '---:' : '---')).join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const pct = (a, b) => (b ? `${((100 * a) / b).toFixed(1)}%` : '–');

const tagged = records.filter((r) => r.unit != null);
const c = coverage.totals;
const covered = (t) => t.topic;
const strict = (t) => t.total - t.untagged;

let out = `# Question analysis

Generated by \`scripts/private/write-reports.mjs\` from \`data-private/question-analysis.json\`, which is private and never committed. This file holds counts and references only, and no wording from any paper.

**${records.length.toLocaleString('en-IN')} question parts** were analysed, from ${paperStats.length} files in \`papers/\`, and tagged with source, question number, sub-part, marks, type, syllabus topic, concepts and formulas tested, skill, structure and common traps. ${paperStats.filter((p) => p.scanned).length} of the files are scanned, and were read with OCR. Twelve scanned pages were also read as images, to compare with what the parser found: they matched closely, with the differences being figures, which OCR can't read.

## Blueprint coverage

A question counts as covered when a blueprint exists with the **same subject, class and syllabus topic, and the same kind of question**.

- **${c.all.outOfSyllabus}** of the ${records.length.toLocaleString('en-IN')} analysed parts are **out of syllabus**, and aren't counted either way: ${records.filter((r) => r.outOfSyllabus && r.subject === 'computerscience').length} on stacks, queues and linked lists in Computer Science, and ${records.filter((r) => r.outOfSyllabus && r.subject === 'mathematics').length} on commerce and regression in Mathematics. They were in papers up to 2025, and the 2028 syllabus doesn't have them.
- **${pct(covered(c.all), c.all.total)}** of the other ${c.all.total.toLocaleString('en-IN')} parts are covered in this sense.
- **${pct(covered(c.all), strict(c.all))}** of the ${strict(c.all).toLocaleString('en-IN')} that could be placed on the 2028 syllabus are covered. The other ${c.all.untagged} couldn't be given a syllabus topic, so no topic can match.
- **${pct(covered(c.all) + c.all.unit + c.all.subject, c.all.total)}** have a blueprint of the same kind somewhere in that subject and class.

${table(['Subject', 'Parts', 'Same topic and kind', 'Of those with a topic', 'Same unit', 'Same subject'], SUBJECTS.map((s) => [LABEL[s], c.subject[s].total, pct(c.subject[s].topic, c.subject[s].total), pct(c.subject[s].topic, strict(c.subject[s])), pct(c.subject[s].unit, c.subject[s].total), pct(c.subject[s].subject, c.subject[s].total)]))}

${table(['Source', 'Parts', 'Same topic and kind', 'Of those with a topic'], Object.entries(c.source).map(([k, t]) => [k, t.total, pct(t.topic, t.total), pct(t.topic, strict(t))]))}

${table(['Style', 'Parts', 'Same topic and kind', 'Of those with a topic'], Object.entries(c.style).map(([k, t]) => [k === 'cbq' ? 'CBQ or competency' : 'Paper', t.total, pct(t.topic, t.total), pct(t.topic, strict(t))]))}

### Blueprints

${blueprints.length.toLocaleString('en-IN')} blueprints ship in \`src/data/blueprints/\`.

${table(['Subject and class', 'Paper-style', 'CBQ-style', 'Total'], SUBJECTS.flatMap((s) => ['XI', 'XII'].map((l) => {
  const here = blueprints.filter((b) => b.subject === s && b.level === l);
  const cbq = here.filter((b) => b.style === 'cbq-style').length;
  return [`${LABEL[s]} ${l}`, here.length - cbq, cbq, here.length];
})))}

### What isn't covered

${coverage.gaps.reduce((sum, g) => sum + g.n, 0)} parts, in ${coverage.gaps.length} combinations, have a syllabus topic but no blueprint of the same kind on that topic. Almost all do have one in the same subject. The largest:

${table(['Parts', 'Subject', 'Class', 'Topic', 'Kind'], coverage.gaps.slice(0, 40).map((g) => [g.n, LABEL[g.what[0]], g.what[1], `${g.what[2]}${g.what[3]} ${g.what[4]}`, KIND[g.what[5]] ?? g.what[5]]))}

${coverage.gaps.length > 40 ? `The other ${coverage.gaps.length - 40} combinations have ${coverage.gaps.slice(40).reduce((s, g) => s + g.n, 0)} parts between them.` : ''}

Why these remain:

- Some come from the topic matcher, not from a real gap. A short reaction or a program fragment has few words to go on, so it can land on the wrong topic. "Complete the program" under Boolean algebra is one of these.
- Chemistry reactions tagged under Solutions or Equivalents are mostly equations asked in passing, which the blueprints for those units ask as numericals.
- A part that needs a figure OCR has lost can only be matched by its words.

## Counts

### By subject and class

${table(['Subject', 'Class XI', 'Class XII', 'Total'], SUBJECTS.map((s) => {
  const here = records.filter((r) => r.subject === s);
  return [LABEL[s], here.filter((r) => r.level === 'XI').length, here.filter((r) => r.level === 'XII').length, here.length];
}))}

### By source

${table(['Source', 'Files', 'Parts'], tally(records, (r) => r.paperType).map(([k, n]) => [k, paperStats.filter((p) => p.type === k).length, n]))}

### By type

${table(['Type', ...SUBJECTS.map((s) => LABEL[s]), 'Total'], tally(records, (r) => r.type).map(([k, n]) => [KIND[k] ?? k, ...SUBJECTS.map((s) => records.filter((r) => r.type === k && r.subject === s).length), n]))}

### By marks

Where the file gives marks for a part. "Not stated" is mostly a sub-part whose marks are given for the whole question, or text where OCR lost them. Marks for a choice question without one are assumed to be 1.

${table(['Marks', ...SUBJECTS.map((s) => LABEL[s]), 'Total'], [...new Set(records.map((r) => r.marks))].sort((a, b) => (a ?? 99) - (b ?? 99)).map((m) => [m ?? 'Not stated', ...SUBJECTS.map((s) => records.filter((r) => r.marks === m && r.subject === s).length), records.filter((r) => r.marks === m).length]))}

### By skill

${table(['Skill', 'Parts'], tally(records, (r) => r.skill ?? 'not clear').map(([k, n]) => [k, n]))}

### By topic

`;
for (const s of SUBJECTS) {
  out += `\n#### ${LABEL[s]}\n\n`;
  const here = tagged.filter((r) => r.subject === s);
  out += table(['Class', 'Topic', 'Parts', 'Blueprints'], tally(here, (r) => `${r.level}|${r.unit}${r.topic}|${r.topicName}`).sort((a, b) => a[0].localeCompare(b[0], 'en', { numeric: true })).map(([k, n]) => {
    const [level, place, name] = k.split('|');
    return [level, `${place} ${name}`, n, blueprints.filter((b) => b.subject === s && b.level === level && `${b.unit}${b.topic}` === place).length];
  }));
  out += '\n';
}

const reasonsOf = tally(unanalysed.flatMap((u) => u.reason.split('; ').map((reason) => ({ ...u, reason }))), (u) => u.reason);
out += `
## Questions that couldn't be fully analysed

${unanalysed.length} entries. A part listed here was still recorded wherever some text survived, and only the listed detail is missing or unreliable.

${table(['Why', 'Entries'], reasonsOf.map(([k, n]) => [k, n]))}

The full list, by file and question number:

`;
const bySource = new Map();
for (const u of unanalysed) bySource.set(u.source, [...(bySource.get(u.source) ?? []), u]);
for (const [source, list] of [...bySource].sort()) {
  const shortReasons = tally(list.flatMap((u) => u.reason.split('; ')), (r) => r);
  out += `- \`${source}\`: ${shortReasons.map(([r, n]) => `${n} ${r.split(':')[0].split(',')[0]}: ${list.filter((u) => u.reason.includes(r)).map((u) => u.question || 'whole file').join(', ')}`).join('; ')}\n`;
}
out += `
## Limits

- This is an automatic analysis checked by sampling. The type and topic of each part come from rules, checked against 12 page images and by reading samples of what each rule caught, and not by a person reading all ${records.length.toLocaleString('en-IN')}.
- Topic tags are best for wordy questions. A bare equation or a short fragment has little to match on.
- The Class XI share is small, as there are few XI papers. XI blueprints lean on the syllabus and the competency questions.
`;
fs.writeFileSync('reports/question-analysis.md', out);

// ---- Physics visuals

const physics = blueprints.filter((b) => b.subject === 'physics');
const withFigure = physics.filter((b) => b.diagram);
const withSim = physics.filter((b) => b.sim);
const NONE = {
  definition: 'Words only: a definition has nothing to draw.',
  reason: 'A reason is asked in words, and a figure would give away the idea behind it.',
  distinguish: 'A comparison of two ideas, with no one set-up to draw.',
  assertion: 'Two statements to weigh. A figure would hint at which is true.',
  mcq: 'A recall question, or one with no geometry.',
  short: 'A statement of a law or a case in words. The case sets the scene itself.',
  derivation: 'The derivation names its own set-up, and part of the work is to draw it.',
  numerical: 'A formula with no geometry to show, such as a material property or a count of particles.',
};
const NONE_LABEL = { definition: 'Definitions', reason: 'Give reasons', distinguish: 'Distinguish between', assertion: 'Assertion and reason', mcq: 'Multiple choice', short: 'Short answers and cases', derivation: 'Derivations', numerical: 'Numericals' };
const row = (b) => [`\`${b.id}\``, b.format, b.diagram ?? '–', b.sim ?? '–'];
let v = `# Physics visuals

Generated by \`scripts/private/write-reports.mjs\`. How each Physics blueprint is drawn: with a generated figure, an embedded simulator, both, or nothing.

**${physics.length} Physics blueprints:** ${withFigure.length} draw a figure, ${withSim.length} of those also open a simulator, and ${physics.filter((b) => !b.diagram && !b.sim).length} have neither.

## How the choice is made

1. **A generated figure**, when the set-up has geometry or a circuit that the words have to describe at length. It's an SVG built from the same values as the question, in \`src/components/bank/BankDiagram.tsx\`. The file loads when the first figure appears.
2. **A simulator as well**, when one exists that can start from this question's values, as in question mode. It's closed by default, as the figure is lighter and enough for most students.
3. **A fixed figure**, for a derivation that always uses the same set-up, drawn with symbols and no numbers. These use the same drawing code, called with letters instead of values, so there's nothing separate to maintain.
4. **Nothing**, when a picture wouldn't help or would answer the question.

## What keeps a figure honest

- **One source of truth.** The figure is built from the question's own values, so it can't disagree with the words. \`tests/unit/physics-visuals.test.ts\` checks every Physics blueprint: each number on the figure must be in the question.
- **It never gives the answer away.** The same test fails if a figure shows a value equal to any answer, unless the question itself states it. A lens or mirror figure has no image and no rays through it, as those are the answer. A rise in a capillary is marked h, and a speed asked for is marked with a question mark.
- **Level energies aren't shown.** The energy-level figure gives only the n values, since the energies are what the question asks you to find.
- **Print and mock papers.** A simulator is never printed or used in a mock paper. Each set-up that has one also has a static figure, so the page makes sense on paper.

## Simulators in question mode

${table(['Simulator', 'Blueprints', 'Before answering?', 'Why'], [
  ['Projectile motion', physics.filter((b) => b.sim === 'projectile').length, 'Yes, with results hidden', 'The path gives a picture, but not the time or range to the required accuracy.'],
  ['Atwood machine', physics.filter((b) => b.sim === 'atwood').length, 'Yes, with results hidden', 'The moving masses show the direction, and not the acceleration.'],
  ['Inclined plane', physics.filter((b) => b.sim === 'inclined').length, 'Yes, with results hidden', 'Shows the block on the slope, and not its acceleration.'],
  ['Spring force and energy', physics.filter((b) => b.sim === 'spring').length, 'Yes, with results hidden', 'Shows the spring stretching, and not the energy.'],
  ['Lens and mirror formula', physics.filter((b) => b.sim === 'lens').length, 'After answering', 'It draws the image, which is the answer.'],
  ['Young’s double slit', physics.filter((b) => b.sim === 'ydse').length, 'After answering', 'It draws the fringes to scale, so the width can be read off.'],
  ['Series LCR resonance', physics.filter((b) => b.sim === 'lcr').length, 'After answering', 'Its curve peaks at the resonant frequency asked for.'],
  ['Snell’s law', physics.filter((b) => b.sim === 'snell').length, 'After answering', 'It would need the refractive index, which is what is asked.'],
  ['Photoelectric effect', physics.filter((b) => b.sim === 'photoelectric').length, 'After answering', 'Its graph shows the kinetic energy.'],
  ['Bohr model', physics.filter((b) => b.sim === 'bohr').length, 'After answering', 'It lists the level energies.'],
  ['Radioactive decay', physics.filter((b) => b.sim === 'radioactive').length, 'After answering', 'Its curve shows what remains at any time.'],
])}

The DC circuit builder, wave superposition, elastic collision, capacitor energy and SHM simulators aren't used in questions. The circuit builder has no way to start from a set circuit, and the others' ranges or models don't match the questions asked (for example, the collision simulator is elastic, and the question is about trolleys that stick together). The figure carries those questions. Each simulator remains available on its own page.

## Every blueprint with a visual

${table(['Blueprint', 'Format', 'Figure', 'Simulator'], physics.filter((b) => b.diagram || b.sim).map(row))}

## Blueprints without a visual, and why

`;
const none = physics.filter((b) => !b.diagram && !b.sim);
for (const [type, reason] of Object.entries(NONE)) {
  const list = none.filter((b) => b.type === type && b.format !== 'diagram');
  if (!list.length) continue;
  v += `**${NONE_LABEL[type]} (${list.length}).** ${reason}\n\n${list.map((b) => `\`${b.id}\``).join(', ')}\n\n`;
}
const draw = none.filter((b) => b.format === 'diagram');
v += `**Asked to draw (${draw.length}).** The question asks you to draw the figure yourself, so showing it would be the answer.\n\n${draw.map((b) => `\`${b.id}\``).join(', ')}\n`;
fs.writeFileSync('reports/physics-visuals.md', v);
console.log('wrote reports', out.length, v.length);
