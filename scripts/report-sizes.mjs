// Reports what the build weighs, and writes reports/bundle-sizes.md.
// Run `npm run build` first.
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';
import { brotliCompressSync, gzipSync } from 'node:zlib';

const DIST = 'dist';

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const measure = (path) => {
  const data = readFileSync(path);
  return { path: relative(DIST, path).replace(/\\/g, '/'), raw: data.length, gzip: gzipSync(data, { level: 9 }).length, brotli: brotliCompressSync(data).length };
};

const files = walk(DIST).map(measure);
const kb = (n) => `${(n / 1024).toFixed(n < 10240 ? 1 : 0)} KB`;
const sum = (list, key) => list.reduce((n, f) => n + f[key], 0);
const named = (pattern) => files.filter((f) => pattern.test(basename(f.path)));

const html = readFileSync(join(DIST, 'index.html'), 'utf8');
const firstNames = new Set([...html.matchAll(/(?:src|href)="\.\/(assets\/[^"]+\.(?:js|css))"/g)].map((m) => m[1]));
firstNames.add('index.html');
const firstLoad = files.filter((f) => firstNames.has(f.path));

const sw = readFileSync(join(DIST, 'sw.js'), 'utf8');
const precached = files.filter((f) => sw.includes(`"${f.path}"`) || sw.includes(`url:"${f.path}"`));

const groups = [
  ['First load: HTML, CSS and JS needed to show the first screen', firstLoad],
  ['JavaScript loaded on first load', firstLoad.filter((f) => f.path.endsWith('.js'))],
  ['CSS loaded on first load', firstLoad.filter((f) => f.path.endsWith('.css'))],
  ['Formula data: all subjects and classes', named(/^(physics|chemistry|mathematics|computerscience)-X/)],
  ['KaTeX code, loaded when the first formula shows', named(/^katex-.*\.js$/)],
  ['KaTeX fonts', named(/^KaTeX_.*\.woff2$/)],
  ['Interface fonts', files.filter((f) => f.path.endsWith('.woff2') && !basename(f.path).startsWith('KaTeX_'))],
  ['Solver registry and maths engine', named(/^(registry|expr)-.*\.js$/)],
  ['Search worker', named(/^worker-.*\.js$/)],
  ['Java tracer', named(/^JavaTracer-.*\.js$/)],
  ['Everything saved for offline use', precached],
];

const lines = ['# Bundle sizes', '', 'Generated by `npm run sizes` from the current `dist/` folder. A web server normally sends the compressed size.', '', '| Part | Files | Raw | Gzip | Brotli |', '| --- | ---: | ---: | ---: | ---: |'];
for (const [label, list] of groups) lines.push(`| ${label} | ${list.length} | ${kb(sum(list, 'raw'))} | ${kb(sum(list, 'gzip'))} | ${kb(sum(list, 'brotli'))} |`);

lines.push('', '## Largest JavaScript files', '', '| File | Raw | Gzip |', '| --- | ---: | ---: |');
const biggest = files.filter((f) => f.path.endsWith('.js') && f.path.startsWith('assets/')).sort((a, b) => b.raw - a.raw).slice(0, 15);
for (const f of biggest) lines.push(`| ${basename(f.path).replace(/-[\w-]{8}\.js$/, '')} | ${kb(f.raw)} | ${kb(f.gzip)} |`);

lines.push('', '## What loads first', '', '| File | Raw | Gzip |', '| --- | ---: | ---: |');
for (const f of [...firstLoad].sort((a, b) => b.gzip - a.gzip)) lines.push(`| ${basename(f.path).replace(/-[\w-]{8}\.(js|css)$/, '.$1')} | ${kb(f.raw)} | ${kb(f.gzip)} |`);

mkdirSync('reports', { recursive: true });
writeFileSync('reports/bundle-sizes.md', `${lines.join('\n')}\n`);
