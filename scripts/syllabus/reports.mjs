// Writes reports/syllabus-report.md and reports/syllabus-review.md.
import fs from 'node:fs';

const LABEL = { physics: 'Physics (861)', chemistry: 'Chemistry (862)', mathematics: 'Mathematics (860)', computerscience: 'Computer Science (868)' };
const SOURCE = {
  physics: 'ISC-2028-Physics.pdf',
  chemistry: '19.-Chemistry.pdf',
  mathematics: '17.-Mathematics.pdf',
  computerscience: '25.-Computer-Science.pdf',
};

function groupBy(items, key) {
  const out = new Map();
  for (const item of items) {
    const k = key(item);
    (out.get(k) ?? out.set(k, []).get(k)).push(item);
  }
  return out;
}

export function writeSyllabusReport(file, { before, archived, classification, manifest, reviewItems }) {
  const lines = ['# Syllabus report', '', 'Generated by `npm run data`. It records what the app was pruned against, and what was taken out.', ''];
  lines.push('## Sources', '');
  lines.push('The four PDFs you supplied in `papers/syllabus/` are the primary source. Each is headed "ISC Examination Year 2028" and dated January 2026, so **each one is the edition for the exact year you sit.** I read all four in full.', '');
  lines.push('| Subject | Document | Edition |', '| --- | --- | --- |');
  for (const [subject, name] of Object.entries(LABEL)) lines.push(`| ${name} | \`papers/syllabus/${SOURCE[subject]}\` | ${manifest.syllabus[subject]} |`);
  lines.push('');
  lines.push('**Checking for a newer edition (accessed 2 November 2026).** I could not read CISCE\'s own listing: `https://cisce.org/?p=9225` and `https://cisce.org/publications/` both refused automated requests with HTTP 403, and I did not try to get around that. Web searches found no 2028 amendment or later edition on cisce.org. The official revision notices they did find are for 2024 to 2026:', '');
  lines.push('- [Circular for Revised Syllabus for Class XI-XII for 2025](https://cisce.org/wp-content/uploads/2024/04/Circular-for-Revised-Syllabus-for-Class-XI-XII-for-2025.pdf)');
  lines.push('- [Prescribed Syllabus in select Subjects for the ISC Year 2024 Examination](https://cisce.org/wp-content/uploads/2023/06/Prescribed-Syllabus-in-select-Subjects-for-the-ISC-Year-2024-Examination.pdf)');
  lines.push('- [Report on the 2026 revision, Careers360](https://news.careers360.com/cisce-isc-class-11-12-syllabus-2026-revised-for-major-subjects-pdf-download-cisce-org/amp) (a news report, not CISCE)');
  lines.push('', '**So please check once by hand:** open cisce.org in a browser, and look under Regulations and Syllabuses for anything newer than January 2026 for the 2028 exams.', '');
  lines.push('## Counts', '', 'Each entry is counted once, at the subject where it was first stored, though it may also be shown in another.', '');
  lines.push('| Subject | Before | Core | Supporting | Uncertain (kept) | Out of syllabus | Not needed | After |', '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |');
  const firstSubject = new Map();
  for (const [subject, ids] of Object.entries(before)) for (const id of ids) if (!firstSubject.has(id)) firstSubject.set(id, subject);
  const totals = { before: 0, core: 0, supporting: 0, review: 0, out: 0, 'not-needed': 0, after: 0 };
  for (const subject of Object.keys(before)) {
    const row = { before: 0, core: 0, supporting: 0, review: 0, out: 0, 'not-needed': 0, after: 0 };
    for (const [id, s] of firstSubject) {
      if (s !== subject) continue;
      row.before++;
      const v = classification[id].verdict;
      row[v]++;
      if (v !== 'out' && v !== 'not-needed') row.after++;
    }
    for (const k of Object.keys(totals)) totals[k] += row[k];
    lines.push(`| ${LABEL[subject]} | ${row.before} | ${row.core} | ${row.supporting} | ${row.review} | ${row.out} | ${row['not-needed']} | ${row.after} |`);
  }
  lines.push(`| **Total** | **${totals.before}** | **${totals.core}** | **${totals.supporting}** | **${totals.review}** | **${totals.out}** | **${totals['not-needed']}** | **${totals.after}** |`);
  const t = manifest.totals;
  lines.push('', `**Reconciliation:** ${t.legacy} in the old app − ${t.merged} merged as repeats − ${t.archived} archived = ${t.entries} now in the app. A test checks this.`, '');
  lines.push('## How entries were classified', '');
  lines.push('- **Core:** in the syllabus, and likely to be used. Everything the solver can calculate, or whose name appears in a paper from 2023 onward, is core.');
  lines.push('- **Supporting:** in the syllabus but minor or derived, such as lists of units and constants.');
  lines.push('- **Out of syllabus:** not covered by the 2028 document. Each has a reason below.');
  lines.push('- **Not needed:** trivial, or not something a student looks up.');
  lines.push('- **Uncertain:** kept in the app, and listed in `reports/syllabus-review.md` for you to decide.', '');
  lines.push('**A conflict in my instructions.** You said anything in the papers is core. But the papers go back to 2017, and the 2028 syllabus has since dropped topics they tested, such as radioactivity and solid state. So when the syllabus leaves something out and a paper includes it, I did not call it core and did not remove it. It went to your review list. A name match is also only a signal: it can be a generic phrase.', '');
  lines.push('**A limit on the evidence.** Board papers test Class XII, so a Class XI topic missing from them proves nothing. Those decisions rest on the syllabus text alone.', '');
  lines.push('Mapping was decided at subtopic level for all 518 subtopics, after reading every formula name, with name-based rules on top. `archive/classification.json` holds the outcome and syllabus topic for every id.', '');
  lines.push('## Removed items, grouped by reason', '');
  lines.push('They are not deleted. `archive/removed-formulas.json` keeps each one with its LaTeX, reason and syllabus reference. It is not shipped in the app.', '');
  for (const subject of Object.keys(LABEL)) {
    const mine = archived.filter((e) => e.subject === subject);
    if (!mine.length) continue;
    lines.push(`### ${LABEL[subject]}: ${mine.length} removed`, '');
    const groups = [...groupBy(mine, (e) => e.reason)].sort((a, b) => b[1].length - a[1].length);
    for (const [reason, items] of groups) {
      lines.push(`**${reason}** (${items.length}${items[0].syllabusReference ? `, ${items[0].syllabusReference}` : ''})`, '');
      lines.push(items.map((e) => e.name).join('; '), '');
    }
  }
  fs.writeFileSync(file, `${lines.join('\n')}\n`);
}

export function writeSyllabusReview(file, { reviewItems }) {
  const items = [...reviewItems.values()];
  const lines = ['# Syllabus items for you to decide', ''];
  lines.push(`These ${items.length} entries are **still in the app**. Nothing here has been removed.`, '');
  lines.push('To remove a group, change its rule from `review` to `out` in `scripts/syllabus/<subject>.mjs` and run `npm run data`. To keep one, make it `supporting`.', '');
  const groups = [...groupBy(items, (e) => e.reason)].sort((a, b) => b[1].length - a[1].length);
  groups.forEach(([reason, members], i) => {
    lines.push(`## ${i + 1}. ${reason}`, '');
    lines.push(`${members.length} ${members.length === 1 ? 'entry' : 'entries'}${members[0].ref ? `. Syllabus reference: ${members[0].ref}` : ''}.`, '');
    for (const e of members) lines.push(`- \`${e.entry.id}\` ${e.entry.name} (${LABEL[e.subject].replace(/ \(\d+\)/, '')} ${e.classLevel}, ${e.unit})`);
    lines.push('');
  });
  fs.writeFileSync(file, `${lines.join('\n')}\n`);
}
