// Runs Lighthouse's mobile preset on the built site, checks that the browser considers
// it installable, and writes reports/lighthouse.md. Run `npm run build` first.
//
// Lighthouse removed its PWA category in version 12, so installability comes from the
// browser itself, through the same check that decides whether to offer "Install app".
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from '@playwright/test';
import lighthouse from 'lighthouse';
import { serveStatic } from './lib/static-server.mjs';

const DEBUG_PORT = 9333;
const PAGES = [
  ['Today', '#/'],
  ['A unit of the book', '#/book/physics/XI/1'],
  ['A formula', '#/f/p-xi-1-7'],
  ['Java tracer', '#/tools/java'],
];
const CATEGORIES = ['performance', 'accessibility', 'best-practices'];

const server = await serveStatic('dist');
const audited = await chromium.launch({ channel: 'msedge', args: [`--remote-debugging-port=${DEBUG_PORT}`] });
const lines = ['# Lighthouse', '', 'Generated by `npm run lighthouse`, with the mobile preset: a mid-range phone on slow 4G, with the CPU slowed to a quarter of its speed. The site is served compressed, as it would be when deployed.', '', '| Page | Performance | Accessibility | Best practices | First contentful paint | Largest contentful paint | Total blocking time | Layout shift |', '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |'];
const failures = [];
let lowestA11y = 100;

for (const [label, hash] of PAGES) {
  const result = await lighthouse(`${server.url}${hash}`, { port: DEBUG_PORT, output: 'json', logLevel: 'error', onlyCategories: CATEGORIES });
  const { categories, audits } = result.lhr;
  const score = (id) => Math.round((categories[id].score ?? 0) * 100);
  lowestA11y = Math.min(lowestA11y, score('accessibility'));
  lines.push(`| ${label} | ${score('performance')} | ${score('accessibility')} | ${score('best-practices')} | ${audits['first-contentful-paint'].displayValue} | ${audits['largest-contentful-paint'].displayValue} | ${audits['total-blocking-time'].displayValue} | ${audits['cumulative-layout-shift'].displayValue} |`);
  for (const id of ['accessibility', 'best-practices']) {
    for (const ref of categories[id].auditRefs) {
      const audit = audits[ref.id];
      if (ref.weight > 0 && audit.score !== null && audit.score < 1) failures.push(`- ${label}, ${id}: ${audit.title}`);
    }
  }
}
await audited.close();

// A normal Playwright context counts as incognito, where nothing can be installed.
const profile = mkdtempSync(join(tmpdir(), 'isc-install-'));
const browser = await chromium.launchPersistentContext(profile, { channel: 'msedge' });
const page = browser.pages()[0] ?? (await browser.newPage());
await page.goto(server.url);
const ready = await page.evaluate(async () => {
  const registration = await navigator.serviceWorker.ready;
  return Boolean(registration.active);
});
const cdp = await browser.newCDPSession(page);
const { installabilityErrors } = await cdp.send('Page.getInstallabilityErrors');
const { errors: manifestErrors } = await cdp.send('Page.getAppManifest');
await browser.close();
rmSync(profile, { recursive: true, force: true });
await server.close();

lines.push('', '## Installable', '');
lines.push(installabilityErrors.length ? `Not installable: ${installabilityErrors.map((e) => e.errorId).join(', ')}.` : 'Yes. Edge reports no installability errors.');
lines.push(`Service worker active: ${ready ? 'yes' : 'no'}. Manifest errors: ${manifestErrors.length}.`);
lines.push('', '## Audits that did not pass', '', failures.length ? [...new Set(failures)].join('\n') : 'None in accessibility or best practices.');

mkdirSync('reports', { recursive: true });
writeFileSync('reports/lighthouse.md', `${lines.join('\n')}\n`);
console.log(lines.slice(4).join('\n'));
process.exit(installabilityErrors.length || lowestA11y < 95 ? 1 : 0);
